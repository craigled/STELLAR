#!/usr/bin/env python3
"""
Bake the flashed STELLAR firmware V0061.37 into web/js/firmware-0061-37.js so the
browser needs no .docx.

V0061.37 is V0061.36 plus the V0061.37 patch set: the whole MA in $17 $33/34 $70/71 $8D $28, 32-bit CVT2DEC $6B,
8-digit CVT2HEX $6C, $A6 $A7 $B1 Z=1 counting from the program in relative mode, version bytes 61 37 -
HW-verified 2026-11-05 (all FW-Checksum-V0061.37 sums match; the six PATCH tests print K). The image comes from
`stellar v6137.hex` (.36 docx + tools/fw_patchset_v37.py) until Craig's V0061.37 docx exists.

V0061.36 is V0061.35 plus the V0061.36 patch set: the error page compacted to $0600-$0656 (every error
site re-pointed; $044B reports $0C), MEMMODE $81 (absolute for the next access only, detour $06DA),
READIDX / WRITEIDX ZX (Z = a register, detour $06E8) and its version bytes 61 36 - HW-verified
2026-10-25 (all FW-Checksum-V0061.36 sums match; PATCH-MEMMODE-81 and PATCH-IDX-Register print K).

V0061.35 is V0061.34 plus the $07 RTC opcode (the DS12887 real-time clock; handler
$2B71-$2DEB) and its version byte - byte-for-byte otherwise (checked 2026-10-03).
The web emulator models the clock chip (stellar-vm.js RTC) from the computer's time.

V0061.34 is V0061.33 with READIDX/WRITEIDX and COPYMXY honouring MEMMODE absolute -
HW-verified 2026-09-25 (PATCH-TEST-U KKKK, all FW-Checksum-V0061.34 sums match).

V0061.33 is V0061.27 (V0061.26 resequenced into document order, patches folded
into their routines) plus the seven opcode-sweep fixes and $F2 SETSIZE (.28),
TESTBITI/TESTMXI rewritten (.29), DEFIN's port check, TESTINP keeping the
defined port and VM state $06 on error (.30), the ADDXYZ / ADDMXMY-SUBMXMY /
COPYIMXA-COPYIAMX fixes (.31), the whole image laid out in strict document order
(.32) and TESTEFI fixed (.33) - HW-verified 2026-09-24 (all FW-Checksum-V0061.33
sums match, PATCH-TEST-T KKKK).
It carries natively every patch this script used to apply by hand
(DIVMAX, OUTDEC, the VM1 launch symmetry, the HEXDEC remainder fix) plus this
session's work: the ADDMXMY/SUBMXMY fixes, the COPYAX/COPYXA, MULTMXMY/DIVMXMY
and cold-conditional-branch merges, the pre-pass length fixes, the LOADZAI Z=0
clamp, and GETSTR at $C2 with RUNMC moved to $F1. So the image is simply the
docx — no manual patching, which removes a whole class of drift between the
flashed firmware and the web simulator.

Emits the non-zero bytes as base64 sparse runs; the JS loader zero-fills the
rest of the 64K image.

    python3 web/build/extract_firmware.py
"""
import os, sys, base64

OUT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                   '..', 'js', 'firmware-0061-37.js'))
FMATH = os.path.expanduser('~/Projects/stellar-1802/Firmware-Math')
sys.path.insert(0, FMATH)
os.chdir(FMATH)                       # load_firmware / parse_lst use relative paths

from load_firmware import load                      # noqa: E402
from divmax_hw_verify import parse_lst              # noqa: E402

def build_image():
    """The V0061.37 image exactly as on the Elf2K, from the official Intel HEX."""
    mem = bytearray(0x10000)
    for ln in open('../stellar v6137.hex'):
        ln = ln.strip()
        if ln.startswith(':'):
            r = bytes.fromhex(ln[1:])
            if r[3] == 0:
                a = (r[1] << 8) | r[2]
                mem[a:a + r[0]] = r[4:4 + r[0]]
    return mem


def runs(mem):
    """Yield (start, bytes) for each maximal run of non-zero bytes."""
    a = 0
    N = len(mem)
    while a < N:
        if mem[a] == 0:
            a += 1; continue
        s = a
        while a < N and mem[a] != 0:
            a += 1
        yield s, bytes(mem[s:a])

def main():
    mem = build_image()
    segs = list(runs(mem))
    out = OUT
    total = sum(len(b) for _, b in segs)
    with open(out, 'w') as f:
        f.write('// AUTO-GENERATED by web/build/extract_firmware.py — do not edit.\n')
        f.write('// STELLAR firmware V0061.37 as flashed, sparse non-zero runs.\n')
        f.write('(function(){\n')
        f.write('  var segs = [\n')
        for s, b in segs:
            f.write('    [0x%04X, "%s"],\n' % (s, base64.b64encode(b).decode()))
        f.write('  ];\n')
        f.write('  var api = { version: "0061.37", segments: segs };\n')
        f.write('  if (typeof module !== "undefined" && module.exports) module.exports = api;\n')
        f.write('  if (typeof window !== "undefined") window.STELLAR_FIRMWARE = api;\n')
        f.write('})();\n')
    print(f'Wrote {out}\n  {len(segs)} runs, {total} firmware bytes '
          f'(${min(s for s,_ in segs):04X}-${max(s+len(b)-1 for s,b in segs):04X})')

if __name__ == '__main__':
    main()
