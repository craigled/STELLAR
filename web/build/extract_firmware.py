#!/usr/bin/env python3
"""
Bake the flashed STELLAR firmware (V0061.22 + DIVMAX/shift-core patches) into
web/js/firmware-0061-22.js so the browser needs no .docx.

Replicates the memory setup that Firmware-Math/calc_interactive.run_calc uses —
minus any application program (apps are loaded at runtime). Emits the non-zero
bytes as base64 sparse runs; the JS loader zero-fills the rest of the 64K image.

    python3 web/build/extract_firmware.py
"""
import os, sys, base64

OUT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                   '..', 'js', 'firmware-0061-22.js'))
FMATH = os.path.expanduser('~/Projects/stellar-1802/Firmware-Math')
sys.path.insert(0, FMATH)
os.chdir(FMATH)                       # load_firmware / parse_lst use relative paths

from load_firmware import load                      # noqa: E402
from divmax_hw_verify import parse_lst              # noqa: E402

def build_image():
    mem, _ = load('../STELLAR MAIN V0061.22.docx')
    for a, b in parse_lst('DIVMAX-hw.lst').items():
        mem[a] = b
    # DIVMAX dispatch + length-table patches (same as calc_interactive)
    mem[0x08B8] = 0x17
    mem[0x08B9] = 0xC0
    mem[0x2E5C] = 0x02
    return mem

def runs(mem):
    """Yield (start, bytes) for each maximal run of non-zero bytes."""
    a = 0
    N = len(mem)
    while a < N:
        if mem[a] == 0:
            a += 1; continue
        s = a
        while a < N and mem[a] != 0:
            a += 1
        yield s, bytes(mem[s:a])

def main():
    mem = build_image()
    segs = list(runs(mem))
    out = OUT
    total = sum(len(b) for _, b in segs)
    with open(out, 'w') as f:
        f.write('// AUTO-GENERATED by web/build/extract_firmware.py — do not edit.\n')
        f.write('// STELLAR firmware V0061.22 + DIVMAX/shift-core patches, sparse non-zero runs.\n')
        f.write('(function(){\n')
        f.write('  var segs = [\n')
        for s, b in segs:
            f.write('    [0x%04X, "%s"],\n' % (s, base64.b64encode(b).decode()))
        f.write('  ];\n')
        f.write('  var api = { version: "0061.22", segments: segs };\n')
        f.write('  if (typeof module !== "undefined" && module.exports) module.exports = api;\n')
        f.write('  if (typeof window !== "undefined") window.STELLAR_FIRMWARE = api;\n')
        f.write('})();\n')
    print(f'Wrote {out}\n  {len(segs)} runs, {total} firmware bytes '
          f'(${min(s for s,_ in segs):04X}-${max(s+len(b)-1 for s,b in segs):04X})')

if __name__ == '__main__':
    main()
